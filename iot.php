import time

broker = 'broker.hivemq.com'
port = 1883
topic = 'iot/sensor'

def on_connect(client, userdata, flags, rc):
    print(f'Connected with result code {rc}')

client = mqtt.Client()
client.on_connect = on_connect
client.connect(broker, port, keepalive=60)
client.loop_start()

while True:
    data = {"temperature": 25, "humidity": 60}
